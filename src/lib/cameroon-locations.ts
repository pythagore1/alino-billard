/** Seule Yaoundé a la livraison standard/express/retrait + le paiement à la livraison. */
export const YAOUNDE_CITY = "Yaoundé";

export function isYaounde(city: string): boolean {
  return city.trim().toLowerCase() === YAOUNDE_CITY.toLowerCase();
}
